def bucket_from_question(item: dict) -> str | None:
    text = " ".join([
        item.get("question", ""),
        item.get("short_answer", ""),
        " ".join(item.get("keywords", [])),
    ])
    for name, needles in QUESTION_RULES:
        if any(needle in text for needle in needles):
            return name
    return None


def bucket_for(label: str) -> str | None:
    """שיוך לפי שם — שם השער בחוברת או ``draft_topic``."""
    text = re.sub(r"\s+", " ", (label or "")).strip()
    if not text:
        return None
    for name, needles in TOPICS:
        if any(needle in text for needle in needles):
            return name
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--units", type=Path, help="book_units.json, לשיוך לפי דמיון")
    args = parser.parse_args()

    groups = json.loads(SEED.read_text(encoding="utf-8"))
    shabbat = next((g for g in groups if g["category"] == "shabbat"), None)
    if shabbat is None:
        print("אין קטגוריית shabbat")
        return 1
    questions = shabbat["questions"]

    # ---- 1. לפי הנושא שנרשם בשעת הכתיבה, ואחריו לפי לשון השאלה -----------
    unresolved: list[dict] = []
    by_name = by_rule = 0
    for item in questions:
        topic = bucket_for(item.get("draft_topic", ""))
        if topic:
            by_name += 1
        else:
            topic = bucket_from_question(item)
            by_rule += topic is not None
        if topic:
            item["topic"] = topic
        else:
            unresolved.append(item)

    # ---- 2. לפי דמיון לשערי החוברת ---------------------------------------
    matched = 0
    if unresolved and args.units and args.units.exists() and (MODEL_DIR / "matrix.npy").exists():
        units = json.loads(args.units.read_text(encoding="utf-8"))["units"]
        pool = [(bucket_for(u["section"]), f"{u['heading']} {u['body'][:400]}") for u in units]
        pool = [(topic, text) for topic, text in pool if topic]
        if pool:
            encoder = Encoder(MODEL_DIR)
            # שכן קרוב יחיד, ולא מרכז של שער: מרכז ממוצע על עשרות הלכות
            # שונות מאבד את מה שמייחד אותן, ובפועל הפך לשואב שמשך אליו
            # שאלות מכל נושא. הדמיון ליחידה בודדת הוא שמבחין.
            matrix = encoder.encode_many([text for _, text in pool])
            vectors = encoder.encode_many([
                f"{q['question']} {q.get('short_answer', '')}" for q in unresolved
            ])
            scores = vectors @ matrix.T
            best = scores.argmax(axis=1)
            for item, index, row in zip(unresolved, best, scores):
                index = int(index)
                # סף: התאמה חלשה אינה שיוך אלא ניחוש, ועדיף עליה "אחר".
                if row[index] >= 0.60:
                    item["topic"] = pool[index][0]
                    matched += 1
                else:
                    item["topic"] = FALLBACK
    else:
        for item in unresolved:
            item["topic"] = FALLBACK

    counts: dict[str, int] = {}
    for item in questions:
        counts[item.get("topic", FALLBACK)] = counts.get(item.get("topic", FALLBACK), 0) + 1

    order = sorted(counts, key=lambda n: BUCKET_OF.get(n, len(TOPICS)))
    print(f"  · {len(questions)} שאלות שבת")
    print(f"  · {by_name} לפי draft_topic, {by_rule} לפי לשון השאלה, {matched} לפי דמיון")
    for name in order:
        print(f"      {counts[name]:4d}  {name}")

    if args.dry_run:
        print("\nדוח בלבד.")
        return 0

    SEED.write_text(json.dumps(groups, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"  · נכתב {SEED.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
